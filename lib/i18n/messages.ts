const arabicMessages: Partial<Record<keyof typeof messages, string>> = messages;

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "ar";
}

export function localeFromCookieValue(value: unknown): Locale {
  return isLocale(value) ? value : "en";
}

export function localeAttributes(locale: Locale) {
  return { lang: locale, dir: locale === "ar" ? "rtl" as const : "ltr" as const };
}

export function translate(locale: Locale, key: string, values: Record<string, string | number> = {}): string {
  const result = locale === "ar" ? (arabicMessages as Record<string, string>)[key] ?? key : key;
  return result.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function localeTag(locale: Locale): string {
  return locale === "ar" ? "ar-QA-u-nu-latn" : "en-GB";
}

export function formatLocaleNumber(locale: Locale, value: number, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(localeTag(locale), options).format(value);
}

export function formatLocaleCurrency(locale: Locale, value: number, currency: string): string {
  return new Intl.NumberFormat(localeTag(locale), { style: "currency", currency, currencyDisplay: "code", maximumFractionDigits: 2 }).format(value);
}

export function formatLocaleDate(locale: Locale, value: Date | string, options: Intl.DateTimeFormatOptions = { dateStyle: "medium" }): string {
  return new Intl.DateTimeFormat(localeTag(locale), options).format(typeof value === "string" ? new Date(value) : value);
}

export const localeCookieName = "aynox_locale";
export const localeCookieMaxAge = 60 * 60 * 24 * 365;

export function localeCookieString(locale: Locale): string {
  return `${localeCookieName}=${locale}; Max-Age=${localeCookieMaxAge}; Path=/; SameSite=Lax`;
}
